export const API_ROUTE_POLICIES = Object.freeze([
  ...publicRoutes,
  ...sessionRoutes,
  ...tenantReadPaths.map((path) => route("GET", path, "tenant", "read")),
  ...tenantReadPatterns,
  ...tenantAdminPaths.map((path) => route("POST", path, "tenant", "admin")),
  ...tenantDraftPaths.map((path) => route("POST", path, "tenant", "draft")),
  ...tenantOperatePaths.map((path) => route("POST", path, "tenant", "operate")),
  ...tenantMutationPatterns,
]);

export function apiRoutePolicy(method, path) {
  return (
    API_ROUTE_POLICIES.find((policy) => policy.method === method && policy.matcher.test(path)) ||
    null
  );
}

function numericRead(template, matcher, sample) {
  return pattern("GET", template, matcher, sample, "tenant", "read");
}

function route(method, path, scope, permission) {
  return pattern(method, path, exact(path), path, scope, permission);
}

function pattern(method, template, matcher, sample, scope, permission) {
  return Object.freeze({
    method,
    template,
    matcher,
    sample,
    scope,
    permission,
    csrf: method !== "GET" && scope !== "public",
  });
}

function exact(path) {
  return new RegExp(`^${path.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}$`);
}
